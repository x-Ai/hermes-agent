// cron.tsx hands runsOnce/runsInterval one of this bundle's own unit words, so
// the read-back can count it the Arabic way ("دقيقتين", "5 دقائق", "15 دقيقة").
const AR_MINUTE = 'دقيقة'
const AR_HOUR = 'ساعة'
const AR_DAY = 'يوم'

const AR_UNITS: Record<string, ArabicCount> = {
  [AR_MINUTE]: { one: 'دقيقة', two: 'دقيقتين', few: '# دقائق', many: '# دقيقة', other: '# دقيقة' },
  [AR_HOUR]: { one: 'ساعة', two: 'ساعتين', few: '# ساعات', many: '# ساعة', other: '# ساعة' },
  [AR_DAY]: { one: 'يوم', two: 'يومين', few: '# أيام', many: '# يومًا', other: '# يوم' }
}

function arUnits(count: number, unit: string): string {
  const forms = AR_UNITS[unit]

  return forms ? arPlural(count, forms) : `${count} ${unit}`
}

